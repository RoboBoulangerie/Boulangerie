"""The GitHub issue forms maintainers use, and turning their answers into croissant edits.

There is one short form for each place a maintainer can say "something's wrong" (a file, a kind of table,
one detail like the license, missing files, ...) plus a general correction form. ``FORMS`` is the single
definition: ``boulangerie write-forms`` generates ``.github/ISSUE_TEMPLATE/*.yml`` from it, and a test keeps
the committed files in sync.

GitHub renders each answer under a ``### <label>`` heading, which is how answers are read back.
"""

import re
from dataclasses import dataclass, field
from urllib.parse import urlencode

import yaml

from boulangerie import paths

NO_RESPONSE = "_No response_"
FEEDBACK_LABEL = "feedback"

KB_FIELD = {
    "type": "input", "id": "kb",
    "attributes": {"label": "Which resource is this about?",
                   "description": "Filled in for you if you came from your resource's page."},
    "validations": {"required": True},
}


@dataclass(frozen=True)
class Form:
    key: str
    name: str  # shown in GitHub's list of forms
    about: str
    title: str  # prefilled issue title; {kb} is replaced
    intro: str
    fields: list[dict] = field(default_factory=list)
    applies_changes: bool = False  # True: answers become a pull request; False: a person reads them
    thanks: str = "Thank you! A member of our team will read this and follow up here."

    @property
    def filename(self) -> str:
        return f"{self.key}.yml"

    def labels(self) -> dict[str, str]:
        """Form label -> field id, for the fields maintainers fill in."""
        return {f["attributes"]["label"]: f["id"] for f in [KB_FIELD, *self.fields]}

    def to_yaml(self) -> str:
        body = [{"type": "markdown", "attributes": {"value": self.intro}}, KB_FIELD, *self.fields]
        form = {"name": self.name, "description": self.about, "title": self.title.replace("{kb}", ""),
                "labels": [FEEDBACK_LABEL], "body": body}
        header = "# Generated by `boulangerie write-forms` from src/boulangerie/feedback.py. Edit that, not this.\n"
        return header + yaml.safe_dump(form, sort_keys=False, allow_unicode=True, width=110)


def _field(kind, field_id, label, description, required):
    attributes = {"label": label, **({"description": description} if description else {})}
    return {"type": kind, "id": field_id, "attributes": attributes, "validations": {"required": required}}


def _textarea(field_id, label, description="", required=False):
    return _field("textarea", field_id, label, description, required)


def _input(field_id, label, description="", required=False):
    return _field("input", field_id, label, description, required)


def _dropdown(field_id, label, options):
    return {"type": "dropdown", "id": field_id, "attributes": {"label": label, "options": options},
            "validations": {"required": True}}


