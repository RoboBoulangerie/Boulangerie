GENERAL_FORM = "croissant-feedback"

# The general form's fields that map straight onto a croissant field.
GENERAL_FIELDS = {
    "name": "name", "description": "description", "license": "license", "citation": "citeAs",
    "access": "conditionsOfAccess", "version": "version",
}


def form_url(repo: str, form_key: str, kb_slug: str, kb_name: str, **prefill: str) -> str:
    form = FORMS[form_key]
    query = {"template": form.filename, "kb": kb_slug, "title": form.title.format(kb=kb_name), **prefill}
    return f"https://github.com/{repo}/issues/new?{urlencode(query)}"


def parse_issue_form(body: str) -> tuple[str, dict[str, str]]:
    """Which form an issue came from, and {field id: answer} for the answered fields."""
    sections = re.split(r"^### +(.+?)\s*$", body.replace("\r\n", "\n"), flags=re.MULTILINE)
    # re.split with one group gives [preamble, heading1, text1, heading2, text2, ...]
    raw = {heading.strip(): text.strip() for heading, text in zip(sections[1::2], sections[2::2])}
    # The form is the one whose labels cover the most headings (every form shares the "resource" question).
    form = max(FORMS.values(), key=lambda f: (len(set(f.labels()) & set(raw)), -len(f.labels())))
    answers = {}
    for label, field_id in form.labels().items():
        value = raw.get(label, "")
        if value and value != NO_RESPONSE:
            answers[field_id] = value
    return form.key, answers


def normalize_license(answer: str) -> str:
    cleaned = answer.strip().strip(".")
    return LICENSE_URLS.get(cleaned.lower(), cleaned)


def requested_changes(form_key: str, answers: dict[str, str]) -> dict[str, str]:
    """Croissant field -> new value, for forms that change the croissant directly."""
    if form_key == GENERAL_FORM:
        return {target: answers[field_id] for field_id, target in GENERAL_FIELDS.items() if field_id in answers}
    if form_key == "fix-detail":
        target = DETAILS.get(answers.get("detail", "").strip())
        return {target: answers["value"]} if target and "value" in answers else {}
    return {}


def apply_feedback(croissant: dict, provenance: dict[str, dict], changes: dict[str, str], issue_url: str,
                   source_url: str = "") -> list[dict]:
    """Apply {croissant field: value} in place. Returns what changed: [{field, old, new}]."""
    applied = []
    for target, new in changes.items():
        if target == "license":
            new = normalize_license(new)
        old = croissant.get(target)
        if old == new:
            continue
        paths.set_value(croissant, target, new)
        provenance[target] = {
            "path": target, "value": new, "url": source_url or issue_url, "confidence": 1.0,
            "source": "maintainer", "issue": issue_url,
        }
        applied.append({"field": target, "old": old, "new": new})
    return applied


def render_pr_body(kb_name: str, issue_number: int, changes: list[dict], answers: dict[str, str], check_summary: str) -> str:
    lines = [
        f"Updates the {kb_name} croissant with the answers from #{issue_number}.",
        "",
        f"Closes #{issue_number}",
        "",
        "## Changes",
        "",
    ]
    for c in changes:
        old = c["old"] if c["old"] not in (None, "") else "_(empty)_"
        lines += [f"**{c['field']}**", "", f"- Before: {old}", f"- After: {c['new']}", ""]
    if "source" in answers:
        lines += [f"Where this is stated: {answers['source']}", ""]
    if "other" in answers:
        lines += ["## Other notes from the maintainer (need a human)", "", answers["other"], ""]
    if "relationship" in answers:
        lines += [f"Submitter's connection to the resource: {answers['relationship']}", ""]
    lines += ["## Checks after this change", "", check_summary]
    return "\n".join(lines)


